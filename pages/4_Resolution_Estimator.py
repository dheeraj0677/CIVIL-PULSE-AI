"""Page 4: Resolution Estimator.
Predictive resolution-time forecasting for new incidents with confidence intervals.
"""

from datetime import datetime
import pandas as pd
import streamlit as st

from src.config import (
    VALID_INCIDENT_TYPES,
    VALID_REPORTED_BY,
    VALID_SEVERITIES,
)
from src.data_loader import load_locations
from src.modeling import load_trained_model
from src.visualization import apply_custom_css, render_kpi_card

apply_custom_css()

st.title("⏱️ Incident Resolution-Time Estimator")
st.markdown("Predictive dispatch tool to forecast turnaround time for emerging infrastructure hazards.")

pipeline, metadata, importance = load_trained_model()

# Graceful check for model artifacts
if pipeline is None:
    st.error(
        "⚠️ Trained model artifacts not found in `artifacts/`. "
        "Please run `python train_model.py` in your terminal to train and serialize the model pipeline."
    )
    st.stop()

# Load location context
@st.cache_data
def get_locations():
    return load_locations()

locations_df = get_locations()

# Explanatory notice
st.markdown(
    """
    <div class='disclaimer-banner'>
        <strong>Operational Transparency:</strong> Predictions are generated by the trained machine learning pipeline 
        (RandomForest Regressor) on historical resolved incidents. Resolution times in this benchmark carry substantial 
        random variance (MAE ~16.4 hours). Always use predictions in conjunction with empirical dispatch protocol.
    </div>
    """,
    unsafe_allow_html=True,
)

# Input Form
with st.form("estimator_form"):
    st.subheader("📝 Incident & Location Dispatch Parameters")
    
    col1, col2 = st.columns(2)
    with col1:
        inc_type = st.selectbox("Incident Type", options=VALID_INCIDENT_TYPES, index=3) # Pothole default
        severity = st.selectbox("Severity Classification", options=VALID_SEVERITIES, index=1) # Medium
        injuries = st.number_input("Injuries Reported", min_value=0, max_value=20, value=0, step=1)
        reported_by = st.selectbox("Reporting Channel", options=VALID_REPORTED_BY, index=1) # Citizen

    with col2:
        loc_choice = st.selectbox(
            "Incident Location",
            options=locations_df["location_id"].tolist(),
            format_func=lambda x: f"{x} ({locations_df[locations_df['location_id']==x]['zone'].iloc[0]} · {locations_df[locations_df['location_id']==x]['road_type'].iloc[0]})",
        )
        report_date = st.date_input("Report Date", value=datetime.today())
        report_hour = st.slider("Report Hour of Day (0-23)", 0, 23, 14)

    submit_btn = st.form_submit_button("⚡ Calculate Estimated Resolution Time")

if submit_btn:
    loc_info = locations_df[locations_df["location_id"] == loc_choice].iloc[0]

    # Build input feature row matching pipeline schema
    sample_data = {
        "incident_type": inc_type,
        "severity": severity,
        "reported_by": reported_by,
        "zone": loc_info["zone"],
        "road_type": loc_info["road_type"],
        "road_condition": loc_info["road_condition"],
        "pedestrian_activity": loc_info["pedestrian_activity"],
        "injuries": int(injuries),
        "near_school": int(loc_info["near_school"]),
        "near_hospital": int(loc_info["near_hospital"]),
        "population_density_per_km2": int(loc_info["population_density_per_km2"]),
        "hour": int(report_hour),
        "day_of_week": int(report_date.weekday()),
        "month": int(report_date.month),
    }

    input_df = pd.DataFrame([sample_data])
    raw_pred = float(pipeline.predict(input_df)[0])
    pred_hours = max(1.0, round(raw_pred, 1))

    # Retrieve test MAE from metadata for empirical confidence interval
    test_mae = metadata.get("test_metrics", {}).get("mae", 16.4)
    low_bound = max(1.0, round(pred_hours - test_mae, 1))
    high_bound = round(pred_hours + test_mae, 1)

    st.markdown("---")
    st.subheader("🎯 Resolution Forecast")

    r1, r2, r3, r4 = st.columns(4)
    with r1:
        render_kpi_card("Point Estimate", f"{pred_hours:.1f} hrs", f"~{pred_hours / 24:.1f} calendar days")
    with r2:
        render_kpi_card("Expected Range (±MAE)", f"{low_bound:.1f} – {high_bound:.1f} hrs", "68% empirical interval")
    with r3:
        render_kpi_card("Location Zone", f"{loc_info['zone']}", f"{loc_info['road_type']} road")
    with r4:
        sens_label = []
        if loc_info["near_school"]:
            sens_label.append("School")
        if loc_info["near_hospital"]:
            sens_label.append("Hospital")
        sens_str = " & ".join(sens_label) if sens_label else "Standard Corridor"
        render_kpi_card("Corridor Sensitivity", sens_str, loc_info["pedestrian_activity"] + " Pedestrians")

    # Operational Dispatch Recommendation
    st.markdown("### 📋 Dispatch Recommendation")
    if severity == "Critical" or injuries > 0:
        st.error(
            f"🚨 **High-Priority Hazard:** Immediate emergency dispatch recommended. "
            f"Casualties ({injuries}) or Critical severity require on-site perimeter securing "
            f"regardless of the estimated {pred_hours:.1f}h standard resolution cycle."
        )
    elif loc_info["near_hospital"] == 1 or loc_info["near_school"] == 1:
        st.warning(
            f"⚠️ **Vulnerable Corridor:** Location `{loc_choice}` sits adjacent to essential municipal infrastructure. "
            f"Schedule crew dispatch within 6 hours to minimize transit disruption."
        )
    else:
        st.success(
            f"✅ **Routine Maintenance Dispatch:** Normal queue dispatch recommended. Expected completion within ~{pred_hours:.1f} hours."
        )
